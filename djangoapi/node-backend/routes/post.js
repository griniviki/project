const express = require("express");
const router = express.Router();
const pool = require("../db");

// GET all posts
router.get("/", (req, res) => {
  res.json(posts);
});

// GET posts by author
router.get("/:author", (req, res) => {
  const author = req.params.author;
  const filtered = posts.filter((p) => p.author === author);
  res.json(filtered);
});

// CREATE a new post
router.post("/", (req, res) => {
  const newPost = { id: posts.length + 1, ...req.body };
  posts.push(newPost);
  res.status(201).json(newPost);
});



// ✅ Get posts with metadata
router.get("/api/post", async (req, res) => {
  try {
    const result = await pool.query(`
      SELECT p.public_id,
             p.body,
             p.linguistics_type,
             p.created,
             p.updated,
             json_agg(
               json_build_object(
                 'language', json_build_object('code', l.code, 'name', l.name),
                 'title', m.title,
                 'body', m.body
               )
             ) AS metadata
      FROM core_post p
      LEFT JOIN core_post_metadata m ON p.public_id = m.post_id
      LEFT JOIN core_language l ON m.language_id = l.code
      GROUP BY p.public_id, p.body, p.linguistics_type, p.created, p.updated
      ORDER BY p.created DESC;
    `);

    res.setHeader("Cache-Control", "no-store"); // prevent caching
    res.json(result.rows);
  } catch (err) {
    console.error("Database error:", err);
    res.status(500).json({ error: err.message });
  }
});

// ✅ Create a new post (UUID generated by PostgreSQL)
router.post("/api/posts", async (req, res) => {
  const { body, linguistics_type } = req.body;
  try {
    const result = await pool.query(
      `INSERT INTO core_post (body, linguistics_type, created, updated)
       VALUES ($1, $2, NOW(), NOW())
       RETURNING public_id, body, linguistics_type, created, updated`,
      [body, linguistics_type]
    );
    res.status(201).json(result.rows[0]);
  } catch (err) {
    console.error("Insert error:", err);
    res.status(500).json({ error: err.message });
  }
});

module.exports = router;